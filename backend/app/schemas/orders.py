def _order_number(value: str) -> str:
    v = value.strip().upper().replace(" ", "")
    if not v.startswith("ORD-"):
        v = f"ORD-{v}"
    if not re.fullmatch(r"ORD-\d{4}-\d{1,8}", v):
        raise ValueError("Enter your order number, e.g. ORD-2026-00012")
    return v


