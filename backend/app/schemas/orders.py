def normalise_qatar_mobile(value: str) -> str:
    """Accept '5512 3456', '+974 5512 3456', '0097455123456'… and return E.164 (+97455123456)."""
    try:
        number = phonenumbers.parse(value.strip(), "QA")
    except phonenumbers.NumberParseException as exc:
        raise ValueError("Enter a valid Qatar mobile number") from exc
    if (
        number.country_code != 974
        or not phonenumbers.is_valid_number(number)
        or phonenumbers.number_type(number)
        not in (phonenumbers.PhoneNumberType.MOBILE, phonenumbers.PhoneNumberType.FIXED_LINE_OR_MOBILE)
    ):
        raise ValueError("Enter a valid Qatar mobile number")
    return phonenumbers.format_number(number, phonenumbers.PhoneNumberFormat.E164)


QatarMobile = Annotated[str, StringConstraints(max_length=30), AfterValidator(normalise_qatar_mobile)]


def _blank_to_none(value: str | None) -> str | None:
    return value or None


class CartLineIn(BaseModel):
    variant_id: int
