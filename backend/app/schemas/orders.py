CouponCode = Annotated[str, StringConstraints(strip_whitespace=True, to_upper=True, min_length=1, max_length=32)]


class CartIn(BaseModel):
    items: list[CartLineIn] = Field(min_length=1, max_length=50)
    coupon_code: CouponCode | None = None
    # Delivery area name (from GET /delivery-areas). Without it the quote has no delivery fee yet.
    delivery_area: Annotated[str | None, StringConstraints(strip_whitespace=True, max_length=120)] = None

    @field_validator("items")
    @classmethod
    def merge_duplicate_variants(cls, items: list[CartLineIn]) -> list[CartLineIn]:
        merged: dict[int, int] = {}
        for line in items:
            merged[line.variant_id] = merged.get(line.variant_id, 0) + line.quantity
        return [CartLineIn(variant_id=v, quantity=q) for v, q in merged.items()]


